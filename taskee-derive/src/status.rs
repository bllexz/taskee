use crate::util::{ext_trait_ident, snake_case};
use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::{Data, DeriveInput, Error, Fields, Ident, Result};

struct Variant {
  name: Ident,
  method: Ident,
  is_terminal: bool,
  args: TokenStream,
  body: TokenStream,
  holes: TokenStream,
}

fn build(variant: &syn::Variant) -> Variant {
  let name = variant.ident.clone();
  let method = format_ident!("{}", snake_case(&name.to_string()), span = name.span());

  let (args, body, holes) = match &variant.fields {
    Fields::Unit => (quote! {}, quote! {}, quote! {}),
    Fields::Unnamed(unnamed) => {
      let names: Vec<Ident> = (0..unnamed.unnamed.len()).map(|i| format_ident!("field{}", i)).collect();
      let types = unnamed.unnamed.iter().map(|field| &field.ty);
      let holes = names.iter().map(|_| quote! { hole() });
      (quote! { #(, #names: #types)* }, quote! { (#(#names),*) }, quote! { (#(#holes),*) })
    }
    Fields::Named(named) => {
      let names: Vec<Ident> = named.named.iter().filter_map(|field| field.ident.clone()).collect();
      let types = named.named.iter().map(|field| &field.ty);
      (quote! { #(, #names: #types)* }, quote! { { #(#names),* } }, quote! { { #(#names: hole()),* } })
    }
  };

  Variant {
    is_terminal: variant.attrs.iter().any(|attr| attr.path().is_ident("terminal")),
    name,
    method,
    args,
    body,
    holes,
  }
}

pub(crate) fn expand(input: DeriveInput) -> Result<TokenStream> {
  let status = &input.ident;
  let visibility = &input.vis;

  let Data::Enum(data) = &input.data else {
    return Err(Error::new_spanned(&input, "`TaskStatus` can only be derived for enums"));
  };

  if !input.generics.params.is_empty() {
    return Err(Error::new_spanned(&input.generics, "`TaskStatus` does not support generic enums"));
  }

  let variants: Vec<Variant> = data.variants.iter().map(build).collect();

  if !variants.iter().any(|variant| variant.is_terminal) {
    return Err(Error::new_spanned(
      &input.ident,
      "`TaskStatus` needs at least one variant marked `#[terminal]`, otherwise the status can never finish the task",
    ));
  }

  let terminal_arms: Vec<TokenStream> = variants
    .iter()
    .filter(|variant| variant.is_terminal)
    .map(|variant| {
      let name = &variant.name;
      quote! { Self::#name { .. } => true }
    })
    .collect();

  let is_terminal = quote! { match self { #(#terminal_arms,)* _ => false } };

  let ext = ext_trait_ident(status);
  let mut declarations = Vec::new();
  let mut definitions = Vec::new();

  for variant in &variants {
    let name = &variant.name;
    let (args, body) = (&variant.args, &variant.body);

    let (method, receiver, target) = if variant.is_terminal {
      (variant.method.clone(), quote! { self }, quote! { ::taskee::AsTask::into_task(self) })
    } else {
      let method = format_ident!("set_{}", variant.method);
      (method, quote! { &self }, quote! { ::taskee::AsTask::as_task(self) })
    };

    let doc = if variant.is_terminal {
      format!("Sets the status to [`{status}::{name}`] and finishes the task.")
    } else {
      format!("Sets the status to [`{status}::{name}`].")
    };

    declarations.push(quote! {
      #[doc = #doc]
      fn #method(#receiver #args);
    });
    definitions.push(quote! {
      #[doc = #doc]
      fn #method(#receiver #args) {
        #target.set_task_status(#status::#name #body);
      }
    });
  }

  let witnesses = variants.iter().map(|Variant { name, holes, .. }| quote! { #status::#name #holes });

  let ext_doc = format!(
    "Typed status setters for any task whose payload holds a [`{status}`].\n\n\
     Import this trait to call them. It covers both a bare `Task<P>` and the \
     wrapper generated by `#[derive(Task)]`."
  );

  Ok(quote! {
    impl ::taskee::TaskStatus for #status {
      fn is_terminal(&self) -> bool {
        #is_terminal
      }
    }

    #[doc = #ext_doc]
    #visibility trait #ext: ::taskee::AsTask {
      #(#declarations)*
    }

    impl<T> #ext for T
    where
      T: ::taskee::AsTask,
      <T as ::taskee::AsTask>::Payload: ::taskee::HasStatus<Status = #status>,
    {
      #(#definitions)*
    }

    const _: () = {
      fn hole<T>() -> T {
        ::core::unreachable!()
      }

      #[allow(dead_code, unreachable_code)]
      fn every_variant_is_constructed_through_the_extension_trait() {
        let _ = [#(#witnesses),*];
      }
    };
  })
}
